// Measures how long each URL in content/consumed.ts takes to get through —
// video length for YouTube, word count at reading speed for articles — and
// regenerates the manifest the page imports. Anything it can't measure is left
// out, and the page falls back to a per-medium estimate.
// Run with: node scripts/fetch-durations.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST = path.join(ROOT, "content", "durations.ts");
const WORDS_PER_MINUTE = 240;
// Fewer words than this means a paywall, a block page, or a JS-rendered shell,
// not a short essay.
const MIN_WORDS = 200;
const CONCURRENCY = 6;

const HEADERS = {
  "User-Agent":
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
  Accept: "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
  "Accept-Language": "en-US,en;q=0.9",
};

function urlsFromContent() {
  const src = fs.readFileSync(path.join(ROOT, "content", "consumed.ts"), "utf8");
  return [...new Set([...src.matchAll(/url:\s*"(https?:\/\/[^"]+)"/g)].map((m) => m[1]))];
}

function previousManifest() {
  if (!fs.existsSync(MANIFEST)) return {};
  const src = fs.readFileSync(MANIFEST, "utf8");
  return Object.fromEntries(
    [...src.matchAll(/^\s*"([^"]+)":\s*(\d+),?$/gm)].map((m) => [m[1], Number(m[2])]),
  );
}

export function isYouTube(url) {
  const host = new URL(url).hostname.replace(/^www\./, "");
  return host === "youtube.com" || host === "youtu.be" || host.endsWith(".youtube.com");
}

export function youTubeMinutes(html) {
  const seconds = html.match(/"lengthSeconds":"(\d+)"/)?.[1];
  return seconds ? Math.max(1, Math.round(Number(seconds) / 60)) : null;
}

export function readingMinutes(html) {
  const body =
    html.match(/<article[\s>][\s\S]*<\/article>/i)?.[0] ??
    html.match(/<main[\s>][\s\S]*<\/main>/i)?.[0] ??
    html;
  const text = body
    .replace(/<(script|style|noscript|svg|nav|header|footer|aside|form)[\s>][\s\S]*?<\/\1>/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/&[a-z#0-9]+;/gi, " ");
  const words = text.split(/\s+/).filter(Boolean).length;
  return words < MIN_WORDS ? null : Math.max(1, Math.round(words / WORDS_PER_MINUTE));
}

async function measure(url) {
  const res = await fetch(url, {
    headers: HEADERS,
    signal: AbortSignal.timeout(20000),
    redirect: "follow",
  });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  if (!(res.headers.get("content-type") ?? "").includes("html")) {
    throw new Error("not HTML");
  }
  const html = await res.text();
  const minutes = isYouTube(url) ? youTubeMinutes(html) : readingMinutes(html);
  if (minutes === null) throw new Error("nothing measurable");
  return minutes;
}

async function main() {
  const urls = urlsFromContent();
  const previous = previousManifest();
  const measured = {};
  const queue = [...urls];

  await Promise.all(
    Array.from({ length: CONCURRENCY }, async () => {
      for (let url = queue.shift(); url; url = queue.shift()) {
        try {
          measured[url] = await measure(url);
          console.log(`${String(measured[url]).padStart(4)} min  ${url}`);
        } catch (err) {
          // A flaky fetch shouldn't throw away a number an earlier run got.
          if (previous[url] !== undefined) measured[url] = previous[url];
          console.warn(`   skip      ${url} (${err.message})`);
        }
      }
    }),
  );

  const lines = Object.keys(measured)
    .sort()
    .map((url) => `  ${JSON.stringify(url)}: ${measured[url]},`);
  fs.writeFileSync(
    MANIFEST,
    `// Generated by scripts/fetch-durations.mjs — do not edit by hand.\n` +
      `export const MINUTES_BY_URL: Record<string, number> = {${lines.length ? `\n${lines.join("\n")}\n` : ""}};\n`,
  );
  console.log(`\n${lines.length}/${urls.length} measured → content/durations.ts`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
